#include <stdio.h>
int main(void)
{
 float h, f, p, w, m;
    float g = 9.80f;
    float n = 0.90f;

    printf("Enter Height of the dam: ");
    scanf("%f", &h);

    printf("Enter Flow rate of water: ");
    scanf("%f", &f);

    m = f * 1000;
    w = m * g * h;
    p = n * w;
    p = p / 1000000;

    printf("Predicted power generated by the hydroelectric dam: %.2f megawatts\n", p);

    return 0;
}
